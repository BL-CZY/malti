    <h3 id="nav">The top bar</h3>
    <p>
        The top bar provides access to the search functionalities. At the main
        page, the search input is placed in the middle of the page. At other
        pages, the input is placed at the center of the top bar. The for buttons
        with ċġħż can help people without access to a Maltese keyboard input
        Maltese, and the three options to the right would dictate which database
        to use while searching.
        <br />
        <br />
        Maltese: Search Maltese only<br />
        English: Search English only<br />
        Both: Search both Maltese and English<br />
    </p>
